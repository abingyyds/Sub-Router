const fallbackActions = actionTranslations.en;

export default Object.fromEntries(
  Object.keys(translations).map((locale) => {
    const values = {
      ...translations[locale],
      ...(actionTranslations[locale] || fallbackActions),
      ...(nodeTranslations[locale] || fallbackNodes),
    };
    return [
      locale,
      Object.fromEntries(
        Object.entries(values).map(([key, value]) => [`nodeStatus.${key}`, value]),
      ),
    ];
  }),
);
